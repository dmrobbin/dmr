MOMENTS = ("start", "player_good", "player_bad", "cpu_good", "cpu_bad", "player_ahead", "cpu_ahead", "win", "lose")


def moments(*values):
    """One CPU's lines for the nine moments, in MOMENTS order: a line, or a list of lines, for each."""
    return {moment: (value if isinstance(value, list) else [value]) for moment, value in zip(MOMENTS, values)}


